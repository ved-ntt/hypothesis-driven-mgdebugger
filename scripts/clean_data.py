"""Clean the seed sets used in the experiments: HumanEvalFix, HumanEval (DeepSeek and StarCoder seeds),
MBPP (DeepSeek seeds).

For every problem it adds, without changing any original field:
  public_tests             the given tests as structured cases (hdmg/public_tests.py reads the forms
                           MGDebugger's parser drops or crashes on)
  public_tests_skipped     asserts that could not be structured, with the reason
  reference_passes_public  the reference solution passes every given test (sanity check on the data)
  detectable               the buggy code fails at least one given test; when False no debugger that
                           sees only the given tests can tell the code is wrong (Finding 2)
  usable                   detectable, at least one given test parsed, and the reference solution passes
                           the given tests (MBPP has a few seeds whose given test calls another function
                           or whose reference fails it). Runs skip problems that are not usable.

Outputs data/clean/<name>.jsonl and results/data_cleaning.md. Runs offline in about a minute.

  python3 scripts/clean_data.py
"""
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, ROOT)
from hdmg.public_tests import parse_public_tests  # noqa: E402
from hdmg.sandbox import run_call                   # noqa: E402

SRC = os.path.join(ROOT, "MGDebugger", "src", "input_data")
SETS = {
    "humanevalfix": os.path.join(SRC, "humanevalfix", "seeds.jsonl"),
    "humaneval_deepseekcoder": os.path.join(SRC, "humaneval", "seed", "deepseekcoder", "seed.jsonl"),
    # held-out sets for variant C (never looked at while designing it): bugs written by other models
    "humaneval_starcoder": os.path.join(SRC, "humaneval", "seed", "starcoder", "seed.jsonl"),
    "mbpp_deepseekcoder": os.path.join(SRC, "mbpp", "seed", "deepseekcoder", "seed.jsonl"),
}


def passes(code: str, asserts: list[str]) -> bool:
    return run_call(code + "\n\n" + "\n".join(asserts), "True", timeout=10)["status"] == "ok"


def clean(path: str) -> list[dict]:
    rows = [json.loads(line) for line in open(path)]
    for r in rows:
        reference = r["prompt"] + r["canonical_solution"]
        # arguments that call helpers (encode_cyclic) are evaluated with the reference program
        parsed, skipped = parse_public_tests(r["given_tests"], r["entry_point"], reference)
        r["public_tests"] = parsed
        r["public_tests_skipped"] = skipped
        r["reference_passes_public"] = passes(reference, r["given_tests"])
        r["detectable"] = (not r["is_solved"]) and not passes(r["solution"], r["given_tests"])
        # usable: a debugger can work on it with the given tests (at least one parsed, and the
        # reference solution passes them). Runs skip problems that are not usable.
        r["usable"] = r["detectable"] and bool(parsed) and r["reference_passes_public"]
    return rows


def main():
    out_dir = os.path.join(ROOT, "data", "clean")
    os.makedirs(out_dir, exist_ok=True)
    report = ["# Data cleaning", "",
              "Generated by `scripts/clean_data.py`. Original seed files are unchanged; cleaned copies are in "
              "`data/clean/`.", "",
              "| Seed set | Problems | Buggy | Detectable | Undetectable | Usable | Public tests | Parsed | "
              "Upstream parser loses | Reference fails public |",
              "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    details = []
    sys.path.insert(0, os.path.join(ROOT, "MGDebugger", "src"))
    from testcase_utils import get_parameter_names, parse_tests  # upstream, for comparison

    for name, path in SETS.items():
        rows = clean(path)
        with open(os.path.join(out_dir, f"{name}.jsonl"), "w") as f:
            for r in rows:
                f.write(json.dumps(r) + "\n")

        buggy = [r for r in rows if not r["is_solved"]]
        detectable = [r for r in buggy if r["detectable"]]
        n_tests = sum(len(r["given_tests"]) for r in rows)
        n_parsed = sum(len(r["public_tests"]) for r in rows)
        upstream_lost = []
        for r in buggy:
            ep = r["entry_point"]
            try:
                params = get_parameter_names(r["prompt"], ep) or get_parameter_names(r["solution"], ep)
                got = len(parse_tests("\n".join(r["given_tests"]).replace(ep, "candidate"), params, ep)["test_cases"])
            except Exception:
                got = -1  # crashes
            if got < len(r["given_tests"]):
                upstream_lost.append((r["task_id"], got, len(r["given_tests"])))
        bad_ref = [r["task_id"] for r in rows if not r["reference_passes_public"]]
        usable = [r for r in buggy if r["usable"]]
        report.append(f"| {name} | {len(rows)} | {len(buggy)} | {len(detectable)} | {len(buggy) - len(detectable)} "
                      f"| {len(usable)} "
                      f"| {n_tests} | {n_parsed} | {len(upstream_lost)} | {len(bad_ref)} |")
        details.append(f"## {name}")
        details.append("")
        details.append("- Undetectable (buggy code passes every given test): "
                       + (", ".join(r["task_id"] for r in buggy if not r["detectable"]) or "none"))
        details.append("- Upstream parser loses or crashes on (task, tests kept, tests given; -1 = crash): "
                       + (", ".join(f"{t} ({g}/{n})" for t, g, n in upstream_lost) or "none"))
        skipped = [(r["task_id"], s) for r in rows for s in r["public_tests_skipped"]]
        details.append("- Not structured by our parser: "
                       + ("; ".join(f"{t}: {s['reason']}" for t, s in skipped) or "none"))
        details.append("- Reference solution fails a given test: " + (", ".join(bad_ref) or "none"))
        details.append("- Detectable but not usable (no given test parsed, or reference fails it): "
                       + (", ".join(r["task_id"] for r in detectable if not r["usable"]) or "none"))
        details.append("")
        print(f"{name}: {len(buggy)} buggy, {len(detectable)} detectable, {n_parsed}/{n_tests} tests parsed, "
              f"upstream loses tests on {len(upstream_lost)}, reference fails public on {len(bad_ref)}")

    report += ["", "Runs skip problems that are not usable (`HDMG_ONLY_DETECTABLE=1`): undetectable bugs, which no "
               "debugger that sees only the given tests can find, and the few with no parsed given test or a "
               "reference solution that fails it. For HumanEvalFix and HumanEval every detectable problem is usable.",
               ""] + details
    with open(os.path.join(ROOT, "results", "data_cleaning.md"), "w") as f:
        f.write("\n".join(report) + "\n")


if __name__ == "__main__":
    main()
